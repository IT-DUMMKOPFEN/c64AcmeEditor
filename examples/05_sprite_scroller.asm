;==============================================================================
;  05 - SPRITE SCROLLER
;------------------------------------------------------------------------------
;  C64 ACME EDITOR example  -  (c) 2026 IT-Dummköpfe  -  MIT License
;
;  A big text scroller made of 8 sprites that are placed side by side. The
;  text is shifted through the sprite graphics bit by bit, and the sprites
;  wave up and down on a sine curve.
;
;  What you can learn here:
;    * double width / double height sprites ($D01D / $D017)
;    * reading the character ROM: switching $01 to make it visible at $D000
;    * multi-byte bit shifting with ASL / ROL (the carry moves the pixel on)
;    * generating repetitive code with ACME's !for loops ("unrolled" loops)
;    * a sine table for the wave movement
;
;  The 8 sprites are 8 x 48 = 384 pixels wide - wider than the screen, so
;  new characters appear invisibly behind the right border.
;==============================================================================

        !to "05_sprite_scroller.prg", cbm

SPRITES     = $2000             ; sprite data for sprites 0-7 ($2000-$21ff)
FIRST_PTR   = SPRITES / 64      ; = 128
SPRITE_PTRS = $07f8
SPEED       = 2                 ; bits per frame (1 bit = 2 pixels here)
BASE_Y      = 130               ; middle of the wave
PI          = 3.14159265

char_ptr    = $fb               ; zero page pointer into the character ROM
text_ptr    = $fd               ; zero page pointer into the scroll text

;------------------------------------------------------------------------------
; BASIC start line: 10 SYS 2061
;------------------------------------------------------------------------------
        * = $0801
        !word +, 10
        !byte $9e
        !text "2061"
        !byte 0
+       !word 0

;------------------------------------------------------------------------------
        !zone main
start
        lda #0
        sta $d020
        sta $d021
        jsr $e544               ; clear screen

        ldx #0                  ; print the title
-       lda title,x
        sta $0400 + 3 * 40 + 6,x
        lda #14                 ; light blue
        sta $d800 + 3 * 40 + 6,x
        inx
        cpx #28
        bne -

        ; ---- clear the sprite graphics -----------------------------------------
        lda #0
        ldx #0
-       sta SPRITES,x
        sta SPRITES + $100,x
        inx
        bne -

        ; ---- set up the 8 sprites ----------------------------------------------
        ldx #7
-       txa
        clc
        adc #FIRST_PTR
        sta SPRITE_PTRS,x       ; sprite n shows data block 128 + n
        dex
        bpl -

        ldx #0
        ldy #0
-       lda xpos,x              ; X positions 0, 48, 96 ... 336 (low bytes)
        sta $d000,y
        iny
        iny
        inx
        cpx #8
        bne -
        lda #%11000000          ; sprites 6 and 7 are at X >= 256
        sta $d010
        lda #%11111111
        sta $d015               ; all sprites on
        sta $d01d               ; double width
        sta $d017               ; double height

        lda #<scroll_text
        sta text_ptr
        lda #>scroll_text
        sta text_ptr + 1
        lda #0
        sta bit_count           ; 0 -> fetch a new character first

; ---- main loop ----------------------------------------------------------------
frame
-       lda $d012               ; wait for raster line $f8 (below the sprites)
        cmp #$f8
        bne -

        ldx #SPEED
.shift  stx shift_count
        lda bit_count           ; all 8 pixel columns of the character used?
        bne +
        jsr next_char
+       jsr shift_sprites       ; move everything one bit to the left
        dec bit_count
        ldx shift_count
        dex
        bne .shift

        jsr wave                ; sine movement + colours

        jsr $ffe4               ; GETIN: SPACE ends the program
        cmp #' '
        bne frame
        lda #0
        sta $d015               ; sprites off
        rts

shift_count !byte 0

;------------------------------------------------------------------------------
; shift_sprites: shift the 8 text lines one pixel to the left.
; For every line: take the next pixel of the current character (ASL puts
; bit 7 into the carry), then ROL through all 24 bytes from right to left.
; This code is generated by ACME: 8 x (1 + 24) instructions.
;------------------------------------------------------------------------------
        !zone shift_sprites
shift_sprites
        !for line, 0, 7 {
            asl char_buffer + line
            !for spr, 0, 7 {
                !for b, 0, 2 {
                    rol SPRITES + (7 - spr) * 64 + line * 3 + (2 - b)
                }
            }
        }
        rts

;------------------------------------------------------------------------------
; next_char: copy the 8 bytes of the next character from the char ROM
;------------------------------------------------------------------------------
        !zone next_char
next_char
        ldy #0
        lda (text_ptr),y        ; screen code of the next character
        cmp #$ff                ; end of text?
        bne +
        lda #<scroll_text
        sta text_ptr
        lda #>scroll_text
        sta text_ptr + 1
        lda (text_ptr),y
+
        ; address in char ROM = $d000 + code * 8
        sta char_ptr
        lda #0
        asl char_ptr            ; 16-bit shift: code * 8
        rol
        asl char_ptr
        rol
        asl char_ptr
        rol
        clc
        adc #$d0
        sta char_ptr + 1

        sei                     ; no interrupts while the I/O area is switched off
        lda $01
        pha
        lda #$33                ; char ROM visible at $d000-$dfff
        sta $01
        ldy #7
-       lda (char_ptr),y
        sta char_buffer,y
        dey
        bpl -
        pla
        sta $01                 ; I/O back
        cli

        inc text_ptr            ; next character of the text
        bne +
        inc text_ptr + 1
+       lda #8
        sta bit_count
        rts

;------------------------------------------------------------------------------
; wave: y position of each sprite from a sine table, cycling colours
;------------------------------------------------------------------------------
        !zone wave
wave
        inc wave_pos
        inc wave_pos
        ldx #0
        ldy #0
-       lda wave_pos
        clc
        adc wave_offset,x       ; each sprite is a bit further on the wave
        sty .save + 1           ; remember Y (self-modifying code)
        tay
        lda sine,y
.save   ldy #0                  ; (operand gets patched above)
        sta $d001,y             ; y position
        iny
        iny
        inx
        cpx #8
        bne -

        lda wave_pos            ; colours
        lsr
        lsr
        lsr
        tay
        ldx #7
-       tya
        and #7
        tay
        lda colors,y
        sta $d027,x
        iny
        dex
        bpl -
        rts

;------------------------------------------------------------------------------
; Data
;------------------------------------------------------------------------------
bit_count   !byte 0
wave_pos    !byte 0
char_buffer !fill 8, 0
xpos        !for i, 0, 7 { !byte <(i * 48) }
wave_offset !for i, 0, 7 { !byte i * 20 }
colors      !byte 7, 13, 3, 14, 4, 10, 8, 15
title       !scr "*** sprite scroller demo ***"

sine        !for i, 0, 255 { !byte BASE_Y + int(30 * sin(float(i) * 2 * PI / 256)) }

scroll_text
        !scr "hey there!  this scroll text is drawn into eight sprites,   "
        !scr "each one stretched to double width and height...    "
        !scr "written with the c64 acme editor by it-dummkoepfe.    "
        !scr "press space to exit.          "
        !byte $ff
