;==============================================================================
;  14 - CHARACTER FIRE
;------------------------------------------------------------------------------
;  C64 ACME EDITOR example  -  (c) 2026 IT-Dummköpfe  -  MIT License
;
;  A burning fire over the whole screen. Every cell has a "heat" value
;  0..63. Each frame the heat rises: a cell gets the average of the cells
;  below it, minus a little cooling. The bottom (invisible) rows are fed
;  with random heat from the SID noise generator.
;
;     heat(x, y) = ( h(x-1, y+1) + h(x, y+1) + h(x+1, y+1) + h(x, y+2) ) / 4 - 1
;
;  The heat selects a dither character (density) and a colour
;  (black - red - orange - yellow - white).
;
;  What you can learn here:
;    * random numbers from the SID: voice 3 with the noise waveform, read $D41B
;    * a 2D buffer with row pointer tables
;    * a custom dither charset generated by ACME (8 densities)
;
;  Further reading on Codebase64:
;    https://codebase64.net/doku.php?id=base:4x4_charset_fire_with_lots_of_colors
;    https://codebase64.net/doku.php?id=base:comparison_of_6502_random_generators
;
;  Press SPACE to return to BASIC.
;==============================================================================

        !to "14_fire.prg", cbm

SCREEN      = $0400
COLORRAM    = $d800
CHARSET     = $3000
D018_VALUE  = %00011100         ; screen $0400, charset $3000
COLS        = 40
ROWS        = 25
BUFROWS     = ROWS + 2          ; 2 hidden rows at the bottom
BUFFER      = $4000             ; heat buffer, 40 x 27 bytes

p_out       = $fb               ; current buffer row
p_below     = $fd               ; buffer row below
p_below2    = $02               ; two rows below ($02/$03)
p_screen    = $04               ; screen row ($04/$05)
p_color     = $06               ; colour row ($06/$07)

;------------------------------------------------------------------------------
; BASIC start line: 10 SYS 2061
;------------------------------------------------------------------------------
        * = $0801
        !word +, 10
        !byte $9e
        !text "2061"
        !byte 0
+       !word 0

;------------------------------------------------------------------------------
        !zone main
start
        lda #0
        sta $d020
        sta $d021
        lda #D018_VALUE
        sta $d018

        ; ---- SID voice 3 as random generator: noise, max frequency ------------
        lda #$ff
        sta $d40e               ; voice 3 frequency lo
        sta $d40f               ; voice 3 frequency hi
        lda #%10000000          ; noise waveform, gate off (silent)
        sta $d412

        ; ---- clear the heat buffer -------------------------------------------------
        lda #0
        tax
-       !for page, 0, 4 {
            sta BUFFER + page * 256,x
        }
        inx
        bne -

frame
        jsr feed                ; random heat into the hidden rows
        jsr burn                ; let the heat rise, draw everything

        jsr $ffe4               ; GETIN: SPACE = exit
        cmp #' '
        bne frame
        lda #$15
        sta $d018
        jmp $e544

;------------------------------------------------------------------------------
; feed: the two hidden rows get random heat (hot spots and cold spots)
;------------------------------------------------------------------------------
        !zone feed
feed
        ldx #COLS - 1
-       lda $d41b               ; random byte from the SID
        and #%00000001          ; every second cell (on average) gets full heat
        bne +
        lda #63
        !byte $2c               ; "bit $xxxx": skips the next 2-byte instruction
+       lda #0
        sta BUFFER + ROWS * COLS,x
        sta BUFFER + (ROWS + 1) * COLS,x
        dex
        bpl -
        rts

;------------------------------------------------------------------------------
; burn: for every visible row from the top down calculate the new heat
;------------------------------------------------------------------------------
        !zone burn
burn
        ldx #0                  ; X = row 0..24
.row
        lda buf_lo,x
        sta p_out
        lda buf_hi,x
        sta p_out + 1
        lda buf_lo + 1,x
        sta p_below
        lda buf_hi + 1,x
        sta p_below + 1
        lda buf_lo + 2,x
        sta p_below2
        lda buf_hi + 2,x
        sta p_below2 + 1
        lda scr_lo,x
        sta p_screen
        sta p_color
        lda scr_hi,x
        sta p_screen + 1
        clc
        adc #>(COLORRAM - SCREEN)
        sta p_color + 1
        stx .savex + 1

        ldy #COLS - 1           ; Y = column (right to left)
.col    lda (p_below),y         ; h(x, y+1)
        clc
        adc (p_below2),y        ; + h(x, y+2)
        dey
        adc (p_below),y         ; + h(x-1, y+1)   (column -1 is the previous row's last byte - fine for a fire)
        iny
        iny
        adc (p_below),y         ; + h(x+1, y+1)
        dey
        lsr                     ; / 4
        lsr
        beq +                   ; cooling: minus 1 (not below 0)
        sec
        sbc #1
+       sta (p_out),y
        tax                     ; heat 0..63 -> character and colour
        lda heat_char,x
        sta (p_screen),y
        lda heat_color,x
        sta (p_color),y
        dey
        bpl .col

.savex  ldx #0
        inx
        cpx #ROWS
        bne .row
        rts

;------------------------------------------------------------------------------
; Tables
;------------------------------------------------------------------------------
buf_lo      !for r, 0, BUFROWS - 1 { !byte <(BUFFER + r * COLS) }
buf_hi      !for r, 0, BUFROWS - 1 { !byte >(BUFFER + r * COLS) }
scr_lo      !for r, 0, ROWS - 1 { !byte <(SCREEN + r * 40) }
scr_hi      !for r, 0, ROWS - 1 { !byte >(SCREEN + r * 40) }

; heat 0..63 -> dither character 0..7 (density) and colour
heat_char   !for h, 0, 63 { !byte h >> 3 }
heat_color  !for h, 0, 63 {
                !if h < 8       { !byte 0 }      ; black
                !if h >= 8  & h < 18 { !byte 9 } ; brown
                !if h >= 18 & h < 28 { !byte 2 } ; red
                !if h >= 28 & h < 38 { !byte 8 } ; orange
                !if h >= 38 & h < 50 { !byte 7 } ; yellow
                !if h >= 50     { !byte 1 }      ; white
            }

;------------------------------------------------------------------------------
; 8 dither characters: character n has about n * 64 / 7 pixels set
; (ordered 4x4 dither matrix, repeated)
;------------------------------------------------------------------------------
        * = CHARSET
        !for n, 0, 7 {
            !set threshold = int(float(n) * 16 / 7 + 0.5)
            !for py, 0, 7 {
                !set bits = 0
                !for px, 0, 7 {
                    !set bx = px & 3
                    !set by = py & 3
                    ; 4x4 Bayer matrix: 0 8 2 10 / 12 4 14 6 / 3 11 1 9 / 15 7 13 5
                    !set m = 4 * (2 * ((bx XOR by) & 1) + (by & 1)) + 2 * (((bx >> 1) XOR (by >> 1)) & 1) + ((by >> 1) & 1)
                    !if m < threshold { !set bits = bits | (128 >> px) }
                }
                !byte bits
            }
        }
