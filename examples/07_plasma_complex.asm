;  07 - COMPLEX PLASMA
;------------------------------------------------------------------------------
;  C64 ACME EDITOR example  -  (c) 2026 IT-Dummköpfe  -  MIT License
;
;  A smoother and richer plasma: five moving sine waves are added together
;  (two along X, two along Y and one diagonal), and the result selects a
;  character with a dither pattern (16 brightness steps) AND a colour.
;
;     value(x, y) = X(x) + Y(y) + D(x + y)       (8 bit, wraps around)
;     X(x) = sinA(3x + t1) + sinB(5x + t2)
;     Y(y) = sinA(4y + t3) + sinB(3y + t4)
;     D(d) = sinA(4d + t5)
;
;  The value is split into 4 colour bands of 64 steps. Inside a band the
;  brightness goes up and down again (0..15..0), so the colour changes
;  exactly where the pattern is dark - no visible edges.
;
;  What you can learn here:
;    * a custom character set ($D018) - generated by ACME with an ordered
;      dither ("Bayer") matrix
;    * self-modifying code: the inner loop gets a new table address per row
;    * table-driven graphics: look-up tables instead of calculations
;    * the ACME XOR operator (note: "^" means "to the power of" in ACME!)
;==============================================================================

        !to "07_plasma_complex.prg", cbm

PI          = 3.14159265
SCREEN      = $0400
COLORRAM    = $d800
CHARSET     = $3000             ; our 16 dither characters
D018_VALUE  = %00011100         ; screen at $0400 (1 * $400), chars at $3000

scr_ptr     = $fb               ; zero page pointers to the current row
col_ptr     = $fd
row_value   = $02               ; Y(y) of the current row

;------------------------------------------------------------------------------
; BASIC start line: 10 SYS 2061
;------------------------------------------------------------------------------
        * = $0801
        !word +, 10
        !byte $9e
        !text "2061"
        !byte 0
+       !word 0

;------------------------------------------------------------------------------
        !zone main
start
        lda #0
        sta $d020
        sta $d021
        lda #D018_VALUE         ; switch to our character set
        sta $d018

frame
        jsr calc_tables         ; X(x), Y(y) and D(d) for this frame
        jsr draw                ; 1000 characters + 1000 colours

        clc                     ; move the five waves at different speeds
        lda t1 : adc #3 : sta t1
        lda t2 : adc #$fe : sta t2      ; ($fe = -2)
        lda t3 : adc #2 : sta t3
        lda t4 : adc #1 : sta t4
        lda t5 : adc #$fd : sta t5      ; ($fd = -3)
        inc cshift

        jsr $ffe4               ; GETIN: SPACE = exit
        cmp #' '
        bne frame
        lda #$15                ; default character set again
        sta $d018
        jmp $e544               ; clear the screen and return to BASIC

;------------------------------------------------------------------------------
; calc_tables: the parts that only depend on x, on y or on x+y
;------------------------------------------------------------------------------
        !zone calc_tables
calc_tables
        ; ---- X(x) for 40 columns -------------------------------------------------
        ldx #0
        lda t1
        sta .a1
        lda t2
        sta .a2
-       ldy .a1
        lda sinA,y
        ldy .a2
        clc
        adc sinB,y
        sta xbuf,x
        lda .a1 : clc : adc #3 : sta .a1
        lda .a2 : clc : adc #5 : sta .a2
        inx
        cpx #40
        bne -

        ; ---- Y(y) for 25 rows ----------------------------------------------------
        ldx #0
        lda t3
        sta .a1
        lda t4
        sta .a2
-       ldy .a1
        lda sinA,y
        ldy .a2
        clc
        adc sinB,y
        sta ybuf,x
        lda .a1 : clc : adc #4 : sta .a1
        lda .a2 : clc : adc #3 : sta .a2
        inx
        cpx #25
        bne -

        ; ---- D(d) for the 64 diagonals (x + y = 0..63) ----------------------------
        ldx #0
        lda t5
        sta .a1
-       ldy .a1
        lda sinA,y
        sta dbuf,x
        lda .a1 : clc : adc #4 : sta .a1
        inx
        cpx #64
        bne -
        rts

.a1     !byte 0
.a2     !byte 0

;------------------------------------------------------------------------------
; draw: value = X(x) + Y(y) + D(x+y)  ->  character + colour
;------------------------------------------------------------------------------
        !zone draw
draw
        lda #<SCREEN : sta scr_ptr
        lda #>SCREEN : sta scr_ptr + 1
        lda #<COLORRAM : sta col_ptr
        lda #>COLORRAM : sta col_ptr + 1
        lda #<dbuf              ; the D() table for row 0 starts at dbuf+0
        sta .diag + 1           ; patch the operand of "adc dbuf,y" below
        lda #>dbuf
        sta .diag + 2

        ldx #0                  ; X = row
.row    lda ybuf,x
        clc
        adc cshift              ; slowly rotate through the colour bands
        sta row_value
        ldy #39                 ; Y = column
.col    lda xbuf,y              ; X(x)
        adc row_value           ; + Y(y)        (we ignore the carry here -
.diag   adc dbuf,y              ; + D(x + y)     an occasional +1 is invisible)
        stx .savex + 1
        tax
        lda chars,x             ; dither character for this value
        sta (scr_ptr),y
        lda colors,x            ; colour for this value
        sta (col_ptr),y
.savex  ldx #0
        dey
        bpl .col

        inc .diag + 1           ; next row: D() table starts one further
        bne +                   ;  (that's the "x + y")
        inc .diag + 2
+       lda scr_ptr             ; pointers + 40
        clc
        adc #40
        sta scr_ptr
        sta col_ptr
        bcc +
        inc scr_ptr + 1
        inc col_ptr + 1
+       inx
        cpx #25
        bne .row
        rts

;------------------------------------------------------------------------------
; Variables and buffers
;------------------------------------------------------------------------------
t1      !byte 0
t2      !byte 40
t3      !byte 80
t4      !byte 120
t5      !byte 160
cshift  !byte 0
xbuf    !fill 40, 0
ybuf    !fill 25, 0
dbuf    !fill 64, 0

;------------------------------------------------------------------------------
; Sine tables. Five of them added must stay below 256 -> values 0..51
; (sinB is a "squeezed" sine with a second harmonic for more variety)
;------------------------------------------------------------------------------
        !align 255, 0
sinA    !for i, 0, 255 { !byte int(25.5 + 25.5 * sin(float(i) * 2 * PI / 256)) }
sinB    !for i, 0, 255 { !byte int(25.5 + 17 * sin(float(i) * 2 * PI / 256) + 8.5 * sin(float(i) * 6 * PI / 256)) }

;------------------------------------------------------------------------------
; chars: value -> dither character 0..15..0 inside every block of 64
; colors: value -> colour of the block (4 colour bands)
;------------------------------------------------------------------------------
chars   !for v, 0, 255 {
            !set t = v & 63
            !if t < 32 { !byte t >> 1 } else { !byte (63 - t) >> 1 }
        }
colors  !for v, 0, 255 {
            !set band = v >> 6
            !if band = 0 { !byte 14 }   ; light blue
            !if band = 1 { !byte 13 }   ; light green
            !if band = 2 { !byte 7 }    ; yellow
            !if band = 3 { !byte 10 }   ; light red
        }

;------------------------------------------------------------------------------
; The character set: char n (0..15) has n * 64 / 15 pixels set, chosen by an
; 8x8 ordered dither matrix:
;   M(x,y) = 16 * m(x,y) + 4 * m(x/2,y/2) + m(x/4,y/4)
;   m(a,b) = 2 * ((a XOR b) AND 1) + (b AND 1)     (the 2x2 Bayer matrix)
; A pixel is set when M(x,y) < threshold.
;------------------------------------------------------------------------------
        * = CHARSET
        !for n, 0, 15 {
            !set threshold = int(float(n) * 64 / 15 + 0.5)
            !for py, 0, 7 {
                !set bits = 0
                !for px, 0, 7 {
                    !set m1 = 2 * ((px XOR py) & 1) + (py & 1)
                    !set m2 = 2 * (((px >> 1) XOR (py >> 1)) & 1) + ((py >> 1) & 1)
                    !set m3 = 2 * (((px >> 2) XOR (py >> 2)) & 1) + ((py >> 2) & 1)
                    !if 16 * m1 + 4 * m2 + m3 < threshold {
                        !set bits = bits | (128 >> px)
                    }
                }
                !byte bits
            }
        }
