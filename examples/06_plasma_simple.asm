;
;  A colourful plasma made of 40 x 25 coloured blocks. The screen is filled
;  with solid blocks (character 160 = inverted space), and only the colour
;  RAM is changed every frame.
;
;  The idea of a plasma:   colour(x, y) = palette[ sin(x) + sin(y) ]
;  When the sine waves move a bit every frame, the colours flow.
;
;  What you can learn here:
;    * colour RAM at $D800 (one colour per character cell)
;    * pre-calculating per-column and per-row values, so the inner loop only
;      has to add two numbers (that's why plasmas can be fast)
;    * indirect indexed addressing: sta (pointer),y
;    * sine tables generated by ACME
;==============================================================================

        !to "06_plasma_simple.prg", cbm

PI          = 3.14159265
SCREEN      = $0400
COLORRAM    = $d800

row_ptr     = $fb               ; zero page pointer to the current colour row
row_value   = $fd               ; sine value of the current row

;------------------------------------------------------------------------------
; BASIC start line: 10 SYS 2061
;------------------------------------------------------------------------------
        * = $0801
        !word +, 10
        !byte $9e
        !text "2061"
        !byte 0
+       !word 0

;------------------------------------------------------------------------------
        !zone main
start
        lda #0
        sta $d020
        sta $d021
        ldx #0                  ; fill the screen with character 160
        lda #160                ; (a solid block: inverted space)
-       sta SCREEN,x
        sta SCREEN + $100,x
        sta SCREEN + $200,x
        sta SCREEN + $2e8,x
        inx
        bne -

frame
        ; ---- 1) values for the 40 columns ---------------------------------------
        ldx phase_x             ; start angle for x
        ldy #0
-       lda sine,x
        sta column_values,y
        txa
        clc
        adc #6                  ; angle step between two columns
        tax
        iny
        cpy #40
        bne -

        ; ---- 2) all 25 rows ------------------------------------------------------
        lda #<COLORRAM
        sta row_ptr
        lda #>COLORRAM
        sta row_ptr + 1
        lda phase_y
        sta angle_y
        ldx #25                 ; row counter
.row
        ldy angle_y
        lda sine,y              ; sine value of this row ...
        clc
        adc color_shift         ; ... plus a slow colour shift
        sta row_value

        ldy #39                 ; 40 columns, from right to left
.col    lda column_values,y
        clc
        adc row_value           ; sin(x) + sin(y)
        stx .savex + 1          ; save X (self-modifying code, faster
        tax                     ;  than pushing it to the stack)
        lda palette,x
.savex  ldx #0
        sta (row_ptr),y
        dey
        bpl .col

        lda row_ptr             ; next row: pointer + 40
        clc
        adc #40
        sta row_ptr
        bcc +
        inc row_ptr + 1
+       lda angle_y
        clc
        adc #9                  ; angle step between two rows
        sta angle_y
        dex
        bne .row

        ; ---- 3) move the waves ---------------------------------------------------
        inc phase_x
        inc phase_x
        inc phase_x
        dec phase_y
        dec phase_y
        inc color_shift
        jmp frame

;------------------------------------------------------------------------------
; Variables
;------------------------------------------------------------------------------
phase_x     !byte 0
phase_y     !byte 0
angle_y     !byte 0
color_shift !byte 0
column_values !fill 40, 0

;------------------------------------------------------------------------------
; sine: 256 values from 0 to 127 (so the sum of two values fits in a byte)
;------------------------------------------------------------------------------
        !align 255, 0
sine
        !for i, 0, 255 { !byte int(63.5 + 63.5 * sin(float(i) * 2 * PI / 256)) }

;------------------------------------------------------------------------------
; palette: 256 colours, 16 bands of 16 entries, smooth brightness steps
;------------------------------------------------------------------------------
palette
        !for band, 0, 15 {
            !set c = 0
            !if band = 0  { !set c = 0 }
            !if band = 1  { !set c = 6 }
            !if band = 2  { !set c = 14 }
            !if band = 3  { !set c = 3 }
            !if band = 4  { !set c = 1 }
            !if band = 5  { !set c = 3 }
            !if band = 6  { !set c = 14 }
            !if band = 7  { !set c = 4 }
            !if band = 8  { !set c = 10 }
            !if band = 9  { !set c = 7 }
            !if band = 10 { !set c = 1 }
            !if band = 11 { !set c = 7 }
            !if band = 12 { !set c = 8 }
            !if band = 13 { !set c = 2 }
            !if band = 14 { !set c = 9 }
            !if band = 15 { !set c = 11 }
            !fill 16, c
        }
